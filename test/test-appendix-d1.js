'use strict';
const assert = require('node:assert/strict');
const { selectCandidates, scoreQuestion, summarize, compare } = require('../scripts/evaluate-appendix-d1');
const item = (lawId, id, score, article) => ({ lawId, id, score, article, text: article, type: 'article' });
const question = { gt: [{ lawId: 4, articles: ['제2조'] }] };
const items = [item(1, 'a', .9, '제1조'), item(1, 'b', .85, '제2조'), item(1, 'c', .84, '제3조'), item(1, 'd', .83, '제4조'),
  item(2, 'a', .8, '제1조'), item(3, 'a', .7, '제1조'), item(4, 'a', .6, '제2조')];
const chosen = selectCandidates(items);
assert.equal(chosen.length, 3);
assert.equal(chosen[0].evidence.length, 3);
assert.deepEqual(chosen.map(r => r.lawId), [1, 2, 3]);
assert.equal(scoreQuestion(question, chosen).strict, false);
const improved = scoreQuestion(question, selectCandidates([...items, item(4, 'b', .95, '제2조')]));
assert.equal(improved.top3, true); assert.equal(improved.strict, true); assert.equal(improved.evidenceHit, null);
const tableQuestion = { gt: [{ lawId: 184, articles: ['별표 1'] }], appendix: '별표 1', row: 3, terms: ['교수', '120'] };
const table = { lawId: 184, evidence: [{ id: 'row', appendix: '별표 1', type: 'table-row', row: 4, text: '교수 | 120' }] };
assert.equal(scoreQuestion(tableQuestion, [table]).strict, true);
assert.equal(scoreQuestion(tableQuestion, [table]).evidenceHit, false);
table.evidence[0].row = 3;
assert.equal(scoreQuestion(tableQuestion, [table]).evidenceHit, true);
const rows = [{ id: 'q', before: { top3: true, strict: true, evidenceHit: null }, after: { top3: true, strict: false, evidenceHit: null } }];
assert.deepEqual(compare(rows, 'before', 'after').strict.newWrong, ['q']);
assert.deepEqual(summarize(rows, 'after').articleGivenTop3, { hits: 0, total: 1 });
assert.deepEqual(summarize(rows, 'after').rowEvidence, { hits: 0, total: 0 });
console.log('appendix D1 scoring: candidate limits, strict/row distinction and regression lists passed');
